async function generateTopic(topicId) {
  const topicData = TOPIC_PASSAGES[topicId];
  const topicEntry = topicsDb[topicId - 1];
  const softTags = topicEntry.soft_tags || {};
  const results = [];

  console.log(`\n=== Topic ${topicId}: ${topicData.topic} (30 days) ===`);

  // 5일씩 묶어서 생성 (API 호출 횟수 줄이기)
  for (let batch = 0; batch < 6; batch++) {
    const startDay = batch * 5 + 1;
    const endDay = Math.min(startDay + 4, 30);
    const batchPassages = topicData.passages.slice(startDay - 1, endDay);

    console.log(`  Days ${startDay}-${endDay}...`);

    for (let i = 0; i < batchPassages.length; i++) {
      const day = startDay + i;
      const passage = batchPassages[i];

      try {
        const result = await callOpenAI([
          { role: 'system', content: SYSTEM_PROMPT },
          { role: 'user', content: buildUserPrompt(topicData.topic, passage, day, softTags) }
        ]);

        const entry = {
          topic: topicData.topic,
          day,
          passage,
          common: {
            background: result.common.background,
            key_verse: result.common.key_verse,
            key_word: result.common.key_word,
            soft_tags: softTags,
            allowed_maturity: ["exploring", "growing", "close", "centered"]
          },
          exploring: {
            ...result.exploring,
            soft_tags: { ...softTags, C01: 100, C02: 10, C03: 10, C04: 40 },
            allowed_maturity: ["exploring"]
          },
          growing: {
            ...result.growing,
            soft_tags: { ...softTags, C01: 95, C02: 25, C03: 30, C04: 50 },
            allowed_maturity: ["growing", "exploring"]
          },
          close: {
            ...result.close,
            cross_reference: result.close.cross_references || result.close.cross_reference || [],
            soft_tags: { ...softTags, C01: 85, C02: 30, C03: 45, C04: 55 },
            allowed_maturity: ["close", "growing"]
          },
          centered: {
            ...result.centered,
            soft_tags: { ...softTags, C01: 85, C02: 15, C03: 40, C04: 70 },
            allowed_maturity: ["centered"]
          },
          passage_meta: parsePassageMeta(passage),
          is_crisis: false
        };

        // close에서 cross_references → cross_reference로 정규화
        if (entry.close.cross_references) {
          delete entry.close.cross_references;
        }

        results.push(entry);
        process.stdout.write(`    Day ${day} ✓  `);
      } catch (e) {
        console.error(`    Day ${day} FAILED:`, e.message?.slice(0, 80));
        // 빈 엔트리라도 넣어서 day 순서 유지
        results.push({
          topic: topicData.topic, day, passage,
          common: { background: "", key_verse: "", key_word: "", soft_tags: softTags, allowed_maturity: ["exploring","growing","close","centered"] },
          exploring: { question_1: "", question_2: "", prayer_guide: "", soft_tags: softTags, allowed_maturity: ["exploring"] },
          growing: { scripture_focus: "", observation: "", application: "", prayer_guide: "", soft_tags: softTags, allowed_maturity: ["growing","exploring"] },
          close: { context: "", observation_deep: "", interpretation: "", application_deep: "", cross_reference: [], soft_tags: softTags, allowed_maturity: ["close","growing"] },
          centered: { lectio: "", meditatio: "", oratio: "", contemplatio: "", actio: "", soft_tags: softTags, allowed_maturity: ["centered"] },
          passage_meta: parsePassageMeta(passage), is_crisis: false
        });
      }

      // Rate limit: ~500ms between calls
      await sleep(500);
    }
    console.log('');
  }

  // 저장
  const outPath = path.join(DATA_DIR, `qt-guides-topic${topicId}.json`);
  fs.writeFileSync(outPath, JSON.stringify(results, null, 2), 'utf8');
  console.log(`  ✅ Saved: qt-guides-topic${topicId}.json (${results.length} days)`);
  return results.length;
}

